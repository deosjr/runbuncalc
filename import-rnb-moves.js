// Regenerates rnb-move-overrides.json from the official Run & Bun "Move Changes"
// sheet. The fork's calc data already carries the base power and type changes,
// but it has no accuracy or effect-chance fields at all, so those have to come
// from here -- 136 moves have a different accuracy in Run & Bun than in vanilla
// gen 8, and trusting @pkmn/dex for them is silently wrong.
//
//   curl -sL "https://docs.google.com/spreadsheets/d/<sheet id>/export?format=csv" -o movechanges.csv
//   node import-rnb-moves.js movechanges.csv
//
// Sheet: Move Changes, from the Run & Bun docs folder.
const fs = require("fs");
const {Dex} = require("@pkmn/dex");

const dex = Dex.forGen(8);
const path = process.argv[2] || "movechanges.csv";
const rows = fs.readFileSync(path, "utf8").split(/\r?\n/).filter(Boolean).map(l => l.split(","));

// names the sheet spells differently from the dex
const aliases = {
	"Precicipe Blades": "Precipice Blades",
};

// "95% > 100%" -> 100, "50 > 30" -> 30
const after = (cell) => {
	if (!cell || cell === "None") return null;
	const m = cell.split(">").pop().trim().replace("%", "");
	const n = Number(m);
	return Number.isFinite(n) ? n : null;
};

const moves = {};
const unmatched = [];
for (const row of rows.slice(1)) {
	const sheetName = (row[0] || "").trim();
	if (!sheetName) continue;
	const name = aliases[sheetName] || sheetName;
	const accuracy = after(row[3]);
	const effectChance = after(row[4]);
	if (accuracy === null && effectChance === null) continue;

	const vanilla = dex.moves.get(name);
	if (!vanilla || !vanilla.exists) { unmatched.push(sheetName); continue; }

	const entry = {};
	if (accuracy !== null) entry.accuracy = accuracy;
	if (effectChance !== null) {
		const secondaries = vanilla.secondaries || [];
		if (secondaries.length === 0) {
			unmatched.push(name + " (effect chance change but no vanilla secondary)");
			continue;
		}
		// every listed move has a single secondary; report rather than assume
		if (secondaries.length > 1)
			unmatched.push(name + " (" + secondaries.length + " secondaries, chance applied to all)");
		// keep the whole vanilla effect and swap only the chance -- these are
		// mostly stat drops (Rock Smash def -1, Octazooka accuracy -1), not statuses
		entry.secondaries = secondaries.map(s => Object.assign({}, s, {chance: effectChance}));
	}
	moves[name] = entry;
}

// the sheet's right-hand table: functional changes that are not power, accuracy
// or effect chance, and that nothing in this model reproduces. Moves listed here
// are reported unverified because the number we have is not the whole story --
// "Thunder Wave: Electric-types cannot miss when using it" is an accuracy rule
// no accuracy field can express.
const functional = {};
for (const row of rows.slice(1)) {
	const name = (row[7] || "").trim();
	if (!name) continue;
	functional[aliases[name] || name] = (row[8] || "").trim().replace(/^"/, "");
}

const out = {
	_comment: [
		"GENERATED by import-rnb-moves.js from the Run & Bun 'Move Changes' sheet.",
		"Do not hand-edit; re-run the importer instead.",
		"",
		"Base power and type changes are NOT here: the fork's own calc data already",
		"carries those, and server.js treats it as authoritative. This file exists",
		"because the calc has no accuracy or effect-chance fields at all.",
		"",
		"The sheet is the complete list of changes, so a move absent from it is",
		"vanilla and can be trusted as such. Only the functional changes below are",
		"reported unverified, because this model does not reproduce them.",
		"",
		"Moves with an accuracy override: " + Object.values(moves).filter(m => m.accuracy !== undefined).length,
		"Moves with an effect-chance override: " + Object.values(moves).filter(m => m.secondaries).length,
		"Moves with unmodelled functional changes: " + Object.keys(functional).length,
	],
	moves,
	functional,
};
fs.writeFileSync("rnb-move-overrides.json", JSON.stringify(out, null, 1) + "\n");
console.log("wrote " + Object.keys(moves).length + " move overrides");
if (unmatched.length) console.log("NEEDS ATTENTION:\n  " + unmatched.join("\n  "));
